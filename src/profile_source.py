"""Profile the original source files and write metadata/source_profile.md.

Run from the project root:  python -m src.profile_source
The source files are only READ here, never changed.
"""
import hashlib

import pandas as pd

from src.config import SETTINGS, path_for, source_file

# the column(s) that should identify one record in each file
BUSINESS_KEYS = {
    "doh-epi-dengue-data-2016-2021.csv": ["loc", "date"],
    "daily_data_combined_2010_to_2019.csv": ["city_name", "datetime"],
    "daily_data_combined_2020_to_2023.csv": ["city_name", "datetime"],
}
DATE_COLUMNS = {"date", "datetime"}


def sha256_of(path):
    """Fingerprint of the file's exact bytes, read in 1 MB chunks."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def column_table(df):
    """One row per column: type, nulls, distinct values, min, max."""
    rows = []
    for col in df.columns:
        s = df[col]
        if col in DATE_COLUMNS:
            values = pd.to_datetime(s, errors="coerce", format="mixed")
        else:
            values = pd.to_numeric(s, errors="coerce")
        # if most values convert, treat the column as numeric/date; else text
        is_typed = values.notna().sum() >= 0.9 * s.notna().sum()
        bad = int((values.isna() & s.notna()).sum()) if is_typed else 0
        rows.append({
            "column": col,
            "pandas_dtype": str(s.dtype),
            "nulls": int(s.isna().sum()),
            "null_pct": round(100 * s.isna().mean(), 2),
            "distinct": int(s.nunique()),
            "min": values.min() if is_typed else "",
            "max": values.max() if is_typed else "",
            "unparseable": bad,
        })
    return pd.DataFrame(rows)


def profile_file(name):
    """Return the markdown section for one source file."""
    path = source_file(name)
    df = pd.read_csv(path, low_memory=False)
    key = BUSINESS_KEYS[name]

    lines = [
        f"## {name}",
        "",
        f"- Location: `data/source/{name}`",
        "- Format: CSV, comma-delimited, UTF-8",
        f"- File size: {path.stat().st_size:,} bytes",
        f"- SHA-256: `{sha256_of(path)}`",
        f"- Rows (excluding header): {len(df):,}",
        f"- Columns: {df.shape[1]}",
        f"- Fully duplicated rows: {int(df.duplicated().sum()):,}",
        f"- Duplicated business key {key}: {int(df.duplicated(subset=key).sum()):,}",
        "",
        column_table(df).to_markdown(index=False),
        "",
    ]
    return "\n".join(lines), df


def target_section(dengue):
    """Distribution of the target (weekly cases) after removing the HXL row."""
    hxl = dengue["loc"].astype(str).str.startswith("#")
    cases = pd.to_numeric(dengue.loc[~hxl, "cases"], errors="coerce")
    lines = [
        "## Target variable: `cases` (weekly dengue cases per location)",
        "",
        f"- HXL tag rows (start with `#`, not data): {int(hxl.sum())}",
        f"- Locations: {dengue.loc[~hxl, 'loc'].nunique()}",
        f"- Weeks with 0 cases: {int((cases == 0).sum()):,} "
        f"({100 * (cases == 0).mean():.1f}%)",
        "",
        cases.describe().round(2).to_frame("cases").to_markdown(),
        "",
        "The distribution is heavily right-skewed (mean far above the median), so the "
        "group used per-city percentile thresholds (33rd/66th) to define the "
        "Low/Moderate/High severity label instead of raw counts.",
        "",
    ]
    return "\n".join(lines)


def main():
    out = ["# Source Profile", "",
           "Generated by `python -m src.profile_source`. Do not edit numbers by hand.", ""]
    dengue = None
    for name in [SETTINGS["source"]["dengue_file"], *SETTINGS["source"]["weather_files"]]:
        print(f"profiling {name} ...")
        section, df = profile_file(name)
        out.append(section)
        if dengue is None:
            dengue = df
    out.append(target_section(dengue))
    notes = path_for("metadata_dir") / "profile_notes.md"
    if notes.exists():
        out.append(notes.read_text(encoding="utf-8"))
    target = path_for("metadata_dir") / "source_profile.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()